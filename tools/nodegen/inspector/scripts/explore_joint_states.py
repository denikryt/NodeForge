"""Inspect joint RNA + Menu configurations and collection.new() capabilities.

Run in Blender (no node IDs or Blender versions are hardcoded):
  blender -b -t 1 --factory-startup --python explore_joint_states.py -- STATES.json OUT.json

STATES.json is generated by explore_states.py using the SAME Blender binary.
For each verified RNA state, discover Menu alternatives in that state; enumerate
all joint Menu assignments and retry each collection.new() argument choice from
RNA metadata in that exact configuration. All mutations occur in a temporary
GeometryNodeTree. No socket-link/context experiments are performed.

Using the text of a TypeError for Menu alternatives is NOT stable Blender API.
Unknown choices are reported as unknown, never represented as exhausted.
"""
import ast
import hashlib
import itertools
import json
import re
import sys
from collections import Counter
from pathlib import Path

import bpy
sys.path.insert(0, str(Path(__file__).resolve().parent))
from blender_rna import sockets, encode, base_props

SENTINEL = '__NODEFORGE_PROBE_INVALID_MENU_CHOICE_82d42b__'
SCHEMA = 'nodeforge.blender_joint_states/1.0'


def error(ex):
    return type(ex).__name__ + ': ' + str(ex)[:400]


def signature(snapshot):
    """Physical socket state: types, positions, labels and all UI availability flags.

    Socket default values are deliberately omitted. Those are configuration values,
    not the topology/availability fingerprint.
    """
    fields = ('index','name','identifier','bl_idname','is_multi_input',
              'is_inactive','is_unavailable','enabled','hide_value')
    raw = [(side, tuple(tuple(x.get(f) for f in fields) for x in snapshot[side]))
           for side in ('inputs','outputs')]
    return hashlib.sha256(repr(raw).encode('utf-8')).hexdigest()[:20]


def keep_snapshot(node, snapshots):
    snap = sockets(node)
    key = signature(snap)
    if key not in snapshots:
        snapshots[key] = snap
    return key


def assign_rna(node, cfg, order):
    for pname in order:
        val = cfg[pname]
        setattr(node, pname, set(val) if isinstance(val, list) else val)
        actual = encode(getattr(node, pname))
        if actual != val:
            raise ValueError('RNA assignment not retained: %s = %r, got %r' % (pname,val,actual))


def new_configured_node(tree, nid, cfg, order, menu_values=None):
    node = tree.nodes.new(nid)
    try:
        assign_rna(node, cfg, order)
        for info in menu_values or []:
            if info['value'] is None:
                continue
            collection = getattr(node, info['side'])
            if info['index'] >= len(collection):
                raise ValueError('Menu socket disappeared: %r' % info)
            skt = collection[info['index']]
            if skt.bl_idname != 'NodeSocketMenu' or skt.identifier != info['identifier']:
                raise ValueError('Menu socket moved/changed: %r' % info)
            skt.default_value = info['value']
            if skt.default_value != info['value']:
                raise ValueError('Menu value not retained: %r' % info)
        # Recheck earlier values, as setting a later Menu can change earlier choices.
        for info in menu_values or []:
            if info['value'] is not None:
                skt = getattr(node,info['side'])[info['index']]
                if skt.default_value != info['value']:
                    raise ValueError('Menu choices interact: %r' % info)
        return node
    except BaseException:
        tree.nodes.remove(node)
        raise


def menu_choices(socket):
    """Read declared RNA values; if absent, parse Blender's diagnostic error."""
    try:
        current = socket.default_value
    except Exception as ex:
        return {'status':'unreadable', 'values':[], 'error':error(ex)}
    values = []
    try:
        p = socket.bl_rna.properties['default_value']
        values = [it.identifier for it in p.enum_items if it.identifier]
    except Exception:
        pass
    if values:
        return {'status':'rna_declared','values':list(dict.fromkeys(values)),'initial':encode(current)}
    try:
        socket.default_value = SENTINEL
        # Unexpected accepted sentinel. Restore and leave possibilities unknown.
        try:
            socket.default_value = current
        except Exception:
            pass
        return {'status':'sentinel_accepted_options_unknown','values':[], 'initial':encode(current)}
    except Exception as ex:
        message = str(ex)
        match = re.search(r'not found in\s*(\([^\n]*\))', message, re.S)
        if match:
            try:
                parsed = ast.literal_eval(match.group(1))
                if isinstance(parsed,tuple) and all(isinstance(x,str) for x in parsed):
                    return {'status':'diagnostic_values' if parsed else 'no_options_in_isolated_context',
                            'values':list(dict.fromkeys(parsed)), 'initial':encode(current)}
            except (ValueError, SyntaxError):
                pass
        return {'status':'options_unknown','values':[], 'initial':encode(current),
                'diagnostic':message[:250]}


def enumerate_menus(node):
    details = []
    for side in ('inputs','outputs'):
        for index, sock in enumerate(getattr(node,side)):
            if sock.bl_idname == 'NodeSocketMenu':
                details.append({'side':side,'index':index,'identifier':sock.identifier,
                                'name':sock.name, **menu_choices(sock)})
    return details


def method_args(method):
    """Build all finite RNA-declared required arguments to `new` (no guessing)."""
    params = [p for p in method.parameters if not p.is_output]
    options = [[]]
    specs = []
    for param in params:
        values = []
        if param.type == 'ENUM':
            values = [item.identifier for item in param.enum_items if item.identifier]
        elif param.type == 'STRING':
            values = ['NodeForge Probe Item']
        elif param.type == 'BOOLEAN':
            values = [False, True]
        elif param.type == 'INT':
            values = [1]
        elif param.type == 'FLOAT':
            values = [1.0]
        specs.append({'name':param.identifier,'type':param.type,
                      'required':bool(param.is_required),
                      'choices':values if param.type == 'ENUM' else None})
        if not param.is_required:
            # No optional arguments are necessary to call a new() method.
            break
        if not values:
            return [], specs, 'required_argument_not_enumerable: '+param.identifier
        options = [base+[choice] for base in options for choice in values]
    return options, specs, None


def collection_descriptions(node):
    descriptions = []
    for p in node.bl_rna.properties:
        if p.type!='COLLECTION' or p.identifier in base_props or p.identifier=='rna_type':
            continue
        try:
            coll = getattr(node,p.identifier)
            method = coll.bl_rna.functions.get('new')
            if method is None or not callable(getattr(coll,'new',None)):
                continue
            args, params, reason = method_args(method)
            descriptions.append({'name':p.identifier, 'length':len(coll),
                                 'new_parameters':params,'candidate_args':args,
                                 'candidate_error':reason})
        except Exception as ex:
            descriptions.append({'name':p.identifier,'error':error(ex)})
    return descriptions


def check_collections(tree, nid, cfg, order, applied_menus, descriptions, snapshots):
    results=[]
    for desc in descriptions:
        row={k:v for k,v in desc.items() if k not in ('candidate_args',)}
        row['attempts']=[]
        for args in desc.get('candidate_args',[]):
            node=None
            trial={'args':args}
            try:
                node=new_configured_node(tree,nid,cfg,order,applied_menus)
                coll=getattr(node,desc['name'])
                trial['before']=keep_snapshot(node,snapshots)
                trial['length_before']=len(coll)
                item=coll.new(*args)
                trial['after']=keep_snapshot(node,snapshots)
                trial['length_after']=len(coll)
                trial['status']='accepted'
                trial['returned_item_type']=getattr(getattr(item,'bl_rna',None),'identifier',type(item).__name__)
                trial['socket_state_changed']=(trial['before']!=trial['after'])
            except Exception as ex:
                trial['status']='rejected';trial['error']=error(ex)
            finally:
                if node is not None: tree.nodes.remove(node)
            row['attempts'].append(trial)
        results.append(row)
    return results


def inspect_node(tree, src):
    nid=src['bl_idname']
    row={'bl_idname':nid,'rna_candidates':src['explored_discrete_assignments'],
         'rna_applied':src['valid_discrete_assignments'],
         'rna_rejected':src['rejected_discrete_assignments'],
         'rna_truncated':not src['discrete_enumeration_complete'],
         'states':[], 'socket_states':{}, 'errors':[]}
    for state_idx, state in enumerate(src['states']):
        if state['status']!='applied':
            continue
        cfg=state['config'];order=state['used_assignment_order']
        base=None
        try:
            base=new_configured_node(tree,nid,cfg,order)
            menu_details=enumerate_menus(base)
        except Exception as ex:
            row['errors'].append({'rna_state_index':state_idx,'error':error(ex)})
            continue
        finally:
            if base is not None:tree.nodes.remove(base)

        # Simple direct product: for this RNA configuration, test each combination
        # of Menu choices reported in that configuration. No socket-link tests.
        axes=[m['values'] if m['values'] else [None] for m in menu_details]
        for values in itertools.product(*axes):
            applied_menus=[{'side':m['side'],'index':m['index'],
                            'identifier':m['identifier'],'value':v}
                           for m,v in zip(menu_details,values)]
            record={'rna_state_index':state_idx,'rna':cfg,
                    'menus':[{'side':m['side'],'index':m['index'],
                              'identifier':m['identifier'],'name':m['name'],
                              'value':v,'discovery_status':m['status'],
                              'possible_values':m['values']}
                             for m,v in zip(menu_details,values)]}
            node=None
            try:
                node=new_configured_node(tree,nid,cfg,order,applied_menus)
                record['status']='applied'
                record['socket_state_id']=keep_snapshot(node,row['socket_states'])
                desc=collection_descriptions(node)
                record['collections']=check_collections(tree,nid,cfg,order,
                                                        applied_menus,desc,row['socket_states'])
            except Exception as ex:
                record['status']='rejected';record['error']=error(ex)
            finally:
                if node is not None:tree.nodes.remove(node)
            row['states'].append(record)
    count=Counter()
    count['combined_states_attempted']=len(row['states'])
    count['combined_states_applied']=sum(s['status']=='applied' for s in row['states'])
    count['combined_states_rejected']=sum(s['status']=='rejected' for s in row['states'])
    count['dynamic_collections_checked']=sum(len(s.get('collections',[])) for s in row['states'])
    count['collection_new_trials']=sum(len(c['attempts']) for s in row['states'] for c in s.get('collections',[]))
    count['collection_new_accepted']=sum(t['status']=='accepted' for s in row['states'] for c in s.get('collections',[]) for t in c['attempts'])
    count['unknown_menu_states']=sum(any(m['value'] is None for m in s['menus']) for s in row['states'])
    row['summary']=dict(count)
    return row


def main(args=None):
    argv=(sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else []) if args is None else args
    if len(argv)!=2:
        raise SystemExit('Usage: blender -b -t 1 --factory-startup --python explore_joint_states.py -- STATES.json OUT.json')
    input_path, output_path=map(Path,argv)
    old=json.loads(input_path.read_text(encoding='utf-8'))
    if old.get('blender_version')!=bpy.app.version_string:
        raise ValueError('RNA source built with %r, but running %r' %
                         (old.get('blender_version'),bpy.app.version_string))
    tree=bpy.data.node_groups.new('NodeForge joint state explorer temporary','GeometryNodeTree')
    result={'schema':SCHEMA,'blender_version':bpy.app.version_string,
            'source_rna_schema':old.get('schema'),
            'method':'RNA applied states x Menu default_value diagnostic enum choices; collection.new trials in every applied joint state',
            'scope':{
                'not_checked':['socket links or zone pairing','numerical ranges and external assets',
                               'element mutation/remove/move in joint states','evaluated geometry and field semantics',
                               'RNA states rejected by Blender',
                               'menu values dependent on links or mutable menu item collections',
                               'Menu options that become available only after assigning a different Menu'],
                'menu_diagnostic_is_unsupported_API':True},
            'nodes':[], 'errors':[]}
    summary=Counter()
    for index,src in enumerate(old['nodes']):
        try:
            r=inspect_node(tree,src)
            result['nodes'].append(r)
            for key,val in r['summary'].items():summary[key]+=val
            summary['nodes_inspected']+=1
            summary['rna_states_rejected_before_joint_probe']+=r['rna_rejected']
            summary['nodes_with_multiple_socket_states']+=len(r['socket_states'])>1
        except Exception as ex:
            result['errors'].append({'node':src['bl_idname'],'error':error(ex)})
        if (index+1)%25==0:
            print('JOINT',index+1,'/',len(old['nodes']),dict(summary),flush=True)
    result['summary']=dict(summary)
    result['summary']['nodes_failed']=len(result['errors'])
    output_path.parent.mkdir(parents=True,exist_ok=True)
    output_path.write_text(json.dumps(result,ensure_ascii=False,separators=(',',':')),
                           encoding='utf-8')
    print('DONE',bpy.app.version_string,dict(result['summary']),flush=True)
    bpy.data.node_groups.remove(tree)

if __name__=='__main__':main()
